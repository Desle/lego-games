import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { parseArgs } from 'node:util'
import { BRICK_DATABASE_PATH, parseBrickDatabase } from '@lego-games/lego-racers/car-builder'
import { openJamArchive } from '@lego-games/lego-racers/jam-archive'
import { readRacerDatabases } from '@lego-games/lego-racers/race'
import { getBrickTemplates } from './brick-templates.ts'
import { loadChampionBodyFaces } from './champion-body-faces.ts'
import { fitOpponentCar } from './fit-opponent-car.ts'
import { OPPONENT_CAR_NOTES } from './opponent-car-notes.ts'
import { getRecord } from './opponent-car-records.ts'
import type { OpponentCarDesign } from './opponent-car.types.ts'

const DEFAULT_JAM_PATH = resolve(
  import.meta.dirname,
  '../../../../../../../original-files/Lego_Racers_Win_Files_EN/Game Files/LEGO.JAM'
)
const DESIGNS_PATH = resolve(import.meta.dirname, 'opponent-car-designs.ts')

const getDesignsSource = (designs: readonly OpponentCarDesign[]): string =>
  [
    "import type { OpponentCarRecord } from './opponent-car.types.ts'",
    '',
    '// Generated by `generate-opponent-car-designs-command.ts` (`pnpm --filter @lego-games/lego-racers-web run opponent-cars`): the fit',
    '// of the catalogue bricks to each champion body, by model name. Notes are kept in `opponent-car-notes.ts`.',
    `export const OPPONENT_CAR_DESIGNS: readonly OpponentCarRecord[] = ${JSON.stringify(designs.map(getRecord))}`,
    '',
  ].join('\n')

// `node generate-opponent-car-designs-command.ts [--only vv,rr] [--jam <LEGO.JAM>] [--write]`: fits every champion's car body (or the
// named ones) and prints how well; `--write` also writes `opponent-car-designs.ts`.
const main = (): number => {
  const { values } = parseArgs({
    args: process.argv.slice(2).filter((argument) => argument !== '--'),
    options: {
      only: { type: 'string' },
      jam: { type: 'string' },
      write: { type: 'boolean' },
    },
  })
  const archive = openJamArchive(new Uint8Array(readFileSync(values.jam ?? DEFAULT_JAM_PATH)))
  const database = parseBrickDatabase(archive.readFile(BRICK_DATABASE_PATH))
  const templates = getBrickTemplates(database)
  const champions = readRacerDatabases((path) => archive.readFile(path)).champions.champions
  const names = values.only?.split(',') ?? champions.map((champion) => champion.name)
  const designs: OpponentCarDesign[] = []
  for (const champion of champions.filter((candidate) => names.includes(candidate.name))) {
    const faces = loadChampionBodyFaces(archive, {
      textureDatabaseName: champion.textureDatabaseName,
      materialLibraryName: champion.materialLibraryName,
      modelName: champion.modelName,
      skeletonName: '',
      animationName: '',
    })
    const { design, quality } = fitOpponentCar(champion.modelName, faces, templates)
    designs.push({ ...design, note: OPPONENT_CAR_NOTES[champion.modelName] ?? '' })
    process.stdout.write(`${champion.name} ${champion.modelName} ${JSON.stringify(quality)}\n`)
  }
  if (values.write === true) writeFileSync(DESIGNS_PATH, getDesignsSource(designs))
  return 0
}

process.exitCode = main()
